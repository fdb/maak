export type Lang = "nl" | "en";
export type Key = keyof typeof nl;

const tables: Record<Lang, Record<Key, string>> = { nl, en };
let current: Lang = "nl";

export function setLang(lang: Lang): void {
  current = lang;
  document.documentElement.lang = lang;
}

export function getLang(): Lang {
  return current;
}

export function t(key: Key, vars: Record<string, string | number> = {}): string {
  return tables[current][key].replace(/\{(\w+)\}/g, (_, name: string) => String(vars[name] ?? ""));
}

/** The message for an error code from the server. */
export function errorText(code: string): string {
  const key = `err.${code}`;
  if (key in nl) return t(key as Key);
  return code.startsWith("path-") ? t("err.path") : t("err.server");
}

export function when(ms: number): string {
  const date = new Date(ms);
  const today = new Date().toDateString() === date.toDateString();
  return date.toLocaleString(current === "nl" ? "nl-BE" : "en-GB", today ? { timeStyle: "short" } : { dateStyle: "medium", timeStyle: "short" });
}

export function size(bytes: number): string {
  return bytes >= 1024 * 1024 ? `${(bytes / 1024 / 1024).toFixed(1)} MB` : `${Math.round(bytes / 1000)} kB`;
}
